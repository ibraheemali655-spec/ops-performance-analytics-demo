"""Test 4: header detection when the separator line is bare commas."""
from __future__ import annotations

from pathlib import Path

from etl.enrich import collect_existing_job_ids

HEADER = "ID,Client > Legal Name,Project Name"


def _write(path: Path, rows: list[str]) -> None:
    body = "Generated by XTRF on 05-04-2026 09:41 GMT+03:00\n"
    body += "," * 19 + "\n"
    body += HEADER + "\n"
    body += "\n".join(rows) + "\n"
    path.write_text(body, encoding="utf-8-sig")


def test_bare_comma_separator_does_not_hide_rows(tmp_path: Path):
    _write(tmp_path / "XTRF-Job-05-04-2026 09_41 GMT+03_00 03_2026.csv",
           ["2026/4083/#3/1,ACME,Proj A", "2026/4084/#3/1,ACME,Proj B"])
    _write(tmp_path / "XTRF-Job-05-05-2026 09_41 GMT+03_00 04_2026.csv",
           ["2026/4099/#3/1,ACME,Proj C"])
    (tmp_path / "not_an_export.txt").write_text("ID should not be picked up here\n")

    ids = collect_existing_job_ids(str(tmp_path), skip_month=4, skip_year=2026)
    assert ids == {"2026/4083/#3/1", "2026/4084/#3/1"}
