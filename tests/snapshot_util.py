"""Shared helpers to craft minimal XTRF-style snapshot folders for unit tests."""
from __future__ import annotations

import csv
from pathlib import Path

JOBS_HEADER = [
    "ID", "Client > Legal Name", "Project Name", "Task > Language Combination > Short Name",
    "Project > Specialization > Name", "Job Type", "Project > Volume", "Deadline", "Job Status",
    "Project > Project Manager > Name", "Vendor > Name", "Vendor > Completed Jobs", "Task > ROI",
    "Total Cost [€]", "Project > Total Agreed [€]", "Project > Margin",
    "Task > Invoice > Invoice No.", "Total Cost", "Project > Total Agreed",
]

PROJECTS_HEADER = [
    "ID", "Name", "Client > Legal Name", "Languages", "Service", "Project Manager > Name",
    "Volume", "Total Cost", "Total Agreed", "Start Date and Time", "Deadline",
    "Total Agreed (without currency)", "Total Agreed [€]", "Margin",
]


def _pad(row: list[str], n: int) -> list[str]:
    return (row + [""] * n)[:n]


def write_snapshot(folder: Path, jobs_rows: list[list[str]], projects_rows: list[list[str]],
                   ts: str = "05-04-2026 09:41") -> None:
    folder.mkdir(parents=True, exist_ok=True)
    jobs = folder / "jobs_analysis.csv"
    with open(jobs, "w", encoding="utf-8-sig", newline="") as f:
        f.write(f"Generated by XTRF on {ts} GMT+03:00\n\n")
        w = csv.writer(f, delimiter=";")
        w.writerow(JOBS_HEADER)
        for r in jobs_rows:
            w.writerow(_pad(r, len(JOBS_HEADER)))
    projects = folder / "projects_default.csv"
    with open(projects, "w", encoding="utf-8-sig", newline="") as f:
        f.write(f"Generated by XTRF on {ts} GMT+03:00\n\n")
        w = csv.writer(f, delimiter=";")
        w.writerow(PROJECTS_HEADER)
        for r in projects_rows:
            w.writerow(_pad(r, len(PROJECTS_HEADER)))


def write_fx(path: Path, rates: dict[str, float]) -> None:
    with open(path, "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow(["month", "eur_usd"])
        for m, r in sorted(rates.items()):
            w.writerow([m, f"{r:.4f}"])


def blank_job(jid: str, deadline: str, cost: str = "€100.00", agreed: str = "€500.00") -> list[str]:
    return [jid, "Test Client", "Proj", "EN-US » FR-FR", "Software", "translation",
            "1,000.00", deadline, "Ready", "PM One", "Vendor A", "12", "100 %",
            cost, agreed, "40 %", "", "100.00", "500.00"]
