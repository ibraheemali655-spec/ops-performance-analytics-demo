"""Offline ETL: turn XTRF-style snapshot exports into a monthly enriched CSV.

Trimmed from the production pipeline: no API fetches (the snapshot folder is the
input), no spreadsheet-download / PBIX / linguist phases, and the FX rate comes from a
local CSV instead of an online service.

Recovers two defects of the source system:

* Late-arriving jobs — a job finalised after its month's snapshot never reached
  that month's export. Every run re-scans the full-history snapshot for rows
  whose Deadline is in an *earlier month of the same year* that no enriched CSV
  holds yet, and appends them at their own month's FX rate.
* Orphan projects — a project with booked revenue and zero rows in the jobs
  view. Every run sweeps January -> target month of the target year for such
  projects, maps each to a job-shaped row via map_project_row, at its own
  month's FX rate. Match on Deadline, falling back to Start Date and Time; when
  matched on Start Date that date is written back into the output Deadline.

CLI:
    python -m etl.enrich --snapshot data/snapshots/2026-03 --month 3 --year 2026 \
        --fx data/fx_rates.csv --out out/jobs
"""
from __future__ import annotations

import argparse
import csv
import glob
import os
import re
import sys
from collections.abc import Callable
from pathlib import Path

PREFIX = "[etl_enrich]"


def _info(msg: str) -> None:
    print(f"{PREFIX} {msg}", flush=True)


# ---------------------------------------------------------------------------
# Parsing primitives
# ---------------------------------------------------------------------------

def parse_euro_value(val: str) -> float | None:
    """Parse a euro-formatted string such as '€1,234.56' into a float, or None."""
    if not val or not val.strip():
        return None
    cleaned = val.replace("€", "").replace(",", "").strip()
    if not cleaned:
        return None
    try:
        return float(cleaned)
    except ValueError:
        return None


def deadline_month_year(deadline_str: str) -> tuple[int, int] | None:
    """(month, year) parsed off a DD-MM-YYYY or YYYY-MM-DD date string, or None."""
    if not deadline_str:
        return None
    patterns = [
        (r"(\d{2})-(\d{2})-(\d{4})", lambda m: (int(m.group(2)), int(m.group(3)))),
        (r"(\d{4})-(\d{2})-(\d{2})", lambda m: (int(m.group(2)), int(m.group(1)))),
    ]
    for pat, extractor in patterns:
        match = re.match(pat, deadline_str)
        if match:
            return extractor(match)
    return None


def deadline_matches_month(deadline_str: str, month: int, year: int) -> bool:
    if not deadline_str:
        return False
    patterns = [
        (r"(\d{2})-(\d{2})-(\d{4})", lambda m: (int(m.group(1)), int(m.group(2)), int(m.group(3)))),
        (r"(\d{4})-(\d{2})-(\d{2})", lambda m: (int(m.group(3)), int(m.group(2)), int(m.group(1)))),
    ]
    for pat, extractor in patterns:
        match = re.match(pat, deadline_str)
        if match:
            day, mon, yr = extractor(match)
            return mon == month and yr == year
    return False


# ---------------------------------------------------------------------------
# Snapshot reading
# ---------------------------------------------------------------------------

def read_semicolon_dump(path: Path) -> tuple[list[str], list[list[str]]]:
    """Read a semicolon-delimited XTRF dump (preamble line, blank line, header, rows)."""
    with open(path, encoding="utf-8-sig", newline="") as f:
        lines = f.read().splitlines()
    header_idx = 0
    for i, line in enumerate(lines):
        stripped = line.strip()
        if not stripped or stripped.startswith("Generated by XTRF"):
            continue
        header_idx = i
        break
    header = next(csv.reader([lines[header_idx]], delimiter=";"))
    rows: list[list[str]] = []
    for line in lines[header_idx + 1:]:
        if not line.strip():
            continue
        row = next(csv.reader([line], delimiter=";"))
        while len(row) < len(header):
            row.append("")
        rows.append(row[: len(header)])
    return header, rows


def parse_projects_rows(path: Path) -> list[dict[str, str]]:
    header, rows = read_semicolon_dump(path)
    return [dict(zip(header, row, strict=False)) for row in rows]


# ---------------------------------------------------------------------------
# Defect recovery logic
# ---------------------------------------------------------------------------

def build_job_project_ids(rows: list[list[str]]) -> set[str]:
    """Every project ID that has at least one row in the Jobs Analysis view.

    A Jobs-view row ID (e.g. "2026/4083/#3/1") is prefixed by its parent
    project's ID exactly as it appears in the Projects-view ID column
    (e.g. "2026/4083") — this is the link key used to detect orphan projects.
    """
    ids: set[str] = set()
    for row in rows:
        jid = (row[0] if row else "").strip()
        if not jid:
            continue
        ids.add(jid.split("/#")[0] if "/#" in jid else jid)
    return ids


def find_orphan_project_rows(
    projects_rows: list[dict[str, str]],
    job_project_ids: set[str],
    target_month: int,
    target_year: int,
    already_captured_ids: set[str],
    from_month: int | None = None,
) -> list[dict[str, str]]:
    """Projects with booked revenue that never produced a row in the Jobs view.

    XTRF's Projects view has no Status column, so "closed with no job" can't be
    read directly; zero matching rows in job_project_ids is the proxy.

    from_month widens the scan to earlier months of the same year (defaults to
    target_month). Orphan projects surface late just as late-arriving Job rows
    do, and a prior month's own run cannot retroactively catch one, so each run
    re-scans the year to date. already_captured_ids must carry every project ID
    any existing enriched CSV already holds, or a prior month's orphan would be
    appended a second time.

    Every returned row carries the month it actually matched on in its
    "Deadline" field, so the caller can pick that month's FX rate.
    """
    start_month = target_month if from_month is None else from_month
    orphans: list[dict[str, str]] = []
    for row in projects_rows:
        pid = row.get("ID", "").strip()
        if not pid or pid in job_project_ids or pid in already_captured_ids:
            continue

        deadline = row.get("Deadline", "").strip()
        start_dt = row.get("Start Date and Time", "").strip()
        for mon in range(start_month, target_month + 1):
            if deadline_matches_month(deadline, mon, target_year):
                orphans.append(row)
                break
            if deadline_matches_month(start_dt, mon, target_year):
                # map_project_row() prefers a non-empty Deadline over Start
                # Date and Time. This row matched via Start Date while its own
                # Deadline is blank or points at an unrelated date (e.g. a
                # stale prior-year value) — write the resolved date back so the
                # output row and the month it was selected for agree.
                row_copy = dict(row)
                row_copy["Deadline"] = start_dt
                orphans.append(row_copy)
                break
    return orphans


def collect_existing_job_ids(output_dir: str, skip_month: int, skip_year: int) -> set[str]:
    """Every task ID already present in an enriched CSV in the output folder.

    Files for the target month itself are skipped: a re-run for the same month
    would otherwise read back the late rows its own previous run appended and
    then decline to re-append them, so deleting the superseded file would drop
    them silently. Skipping keeps the transform idempotent per month.
    """
    ids: set[str] = set()
    suffix = f"{skip_month:02d}_{skip_year}"
    for path in glob.glob(os.path.join(output_dir, "XTRF-Job-*.csv")):
        if suffix in os.path.basename(path):
            continue
        try:
            with open(path, encoding="utf-8-sig") as f:
                lines = f.read().splitlines()
        except OSError:
            continue
        # The separator line under the "Generated by XTRF" preamble is not
        # empty — it is a row of bare commas — so find the header by its first
        # field rather than by skipping blanks.
        header_idx = None
        id_idx = None
        for i, line in enumerate(lines[:10]):
            try:
                fields = next(csv.reader([line], delimiter=","))
            except StopIteration:
                continue
            if fields and fields[0].strip() == "ID":
                header_idx = i
                id_idx = 0
                break
        if header_idx is None:
            continue
        for line in lines[header_idx + 1:]:
            if not line.strip():
                continue
            try:
                row = next(csv.reader([line], delimiter=","))
            except StopIteration:
                continue
            if len(row) > id_idx and row[id_idx].strip():
                ids.add(row[id_idx].strip())
    return ids


def find_late_job_rows(
    all_job_rows: list[list[str]],
    existing_ids: set[str],
    id_idx: int,
    deadline_idx: int,
    euro_idxs: list[int],
    target_month: int,
    target_year: int,
    fx_for_month: Callable[[int, int], float],
) -> tuple[list[list[str]], dict[int, int]]:
    """Jobs-view rows for *earlier* months of the target year that no enriched
    CSV holds yet.

    Each monthly enriched CSV is a point-in-time snapshot taken shortly after
    that month closes. A job finalised in XTRF after its own month's snapshot
    was written never enters the folder at all. Rows are converted at *their
    own* month's FX rate, not the target month's, so the USD figures match what
    that month's own run would have produced.
    """
    late_rows: list[list[str]] = []
    per_month: dict[int, int] = {}
    for row in all_job_rows:
        tid = row[id_idx].strip() if len(row) > id_idx else ""
        if not tid or tid in existing_ids:
            continue
        my = deadline_month_year(row[deadline_idx])
        if not my:
            continue
        mon, yr = my
        if yr != target_year or mon >= target_month:
            continue

        row = list(row)
        rate = fx_for_month(mon, yr)
        for ci in euro_idxs:
            parsed = parse_euro_value(row[ci])
            if parsed is not None:
                row[ci] = f"{parsed * rate:.5f}"
        late_rows.append(row)
        per_month[mon] = per_month.get(mon, 0) + 1
    return late_rows, per_month


def map_project_row(proj_row: dict[str, str], fx_rate: float) -> list[str]:
    """Map a Projects-view row onto the 19-column job-row layout."""
    agreed_val = parse_euro_value(proj_row.get("Total Agreed [€]", "").strip())
    total_agreed_usd = f"{agreed_val * fx_rate:.5f}" if agreed_val is not None else ""

    return [
        proj_row.get("ID", "").strip(),
        proj_row.get("Client > Legal Name", "").strip(),
        proj_row.get("Name", "").strip(),
        proj_row.get("Languages", "").strip(),
        "General",
        "TEP",
        proj_row.get("Volume", "").strip(),
        proj_row.get("Deadline", "").strip(),
        "Ready",
        proj_row.get("Project Manager > Name", "").strip(),
        "Vendor",
        "",
        "",
        "",
        total_agreed_usd,
        proj_row.get("Margin", "").strip(),
        "",
        "",
        "",
    ]


# ---------------------------------------------------------------------------
# FX + snapshot metadata
# ---------------------------------------------------------------------------

def load_fx_rates(path: Path) -> dict[tuple[int, int], float]:
    rates: dict[tuple[int, int], float] = {}
    with open(path, encoding="utf-8-sig", newline="") as f:
        for row in csv.DictReader(f):
            y, m = row["month"].split("-")
            rates[(int(y), int(m))] = float(row["eur_usd"])
    return rates


def snapshot_timestamp(path: Path) -> tuple[str, str, str, str, str]:
    """The 'Generated by XTRF on <dd-mm-yyyy HH:MM>' line of a jobs dump.

    Returns (dd, mm, yyyy, hh, minute) as zero-padded strings.
    """
    with open(path, encoding="utf-8-sig") as f:
        first = f.readline().strip()
    match = re.match(r"Generated by XTRF on (\d{2})-(\d{2})-(\d{4}) (\d{2}):(\d{2})", first)
    if not match:
        raise ValueError(f"no XTRF timestamp preamble in {path}: {first!r}")
    dd, mm, yyyy, hh, min_ = match.groups()
    return dd, mm, yyyy, hh, min_


# ---------------------------------------------------------------------------
# Transform
# ---------------------------------------------------------------------------

def run(snapshot_dir: Path, month: int, year: int, fx_path: Path, output_dir: Path) -> dict:
    """Enrich one month. Returns a summary dict; the CLI is a thin wrapper."""
    snapshot_dir = Path(snapshot_dir)
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    rates = load_fx_rates(Path(fx_path))
    if (year, month) not in rates:
        raise KeyError(f"no FX rate for {year}-{month:02d} in {fx_path}")
    fx_rate = rates[(year, month)]

    def fx_for_month(m: int, y: int) -> float:
        # Never fall back to the target month's rate: a missing rate for the
        # row's own month must fail loudly, or USD figures are silently wrong.
        try:
            return rates[(y, m)]
        except KeyError:
            raise KeyError(f"no FX rate for {y}-{m:02d} in {fx_path}") from None

    jobs_path = snapshot_dir / "jobs_analysis.csv"
    header, all_rows = read_semicolon_dump(jobs_path)

    euro_idxs = [idx for idx, col in enumerate(header) if "€" in col]
    deadline_idx = next(idx for idx, c in enumerate(header) if c.strip() == "Deadline")
    id_idx = next(idx for idx, c in enumerate(header) if c.strip() == "ID")

    data_rows: list[list[str]] = []
    for row in all_rows:
        if not deadline_matches_month(row[deadline_idx], month, year):
            continue
        row = list(row)
        for ci in euro_idxs:
            parsed = parse_euro_value(row[ci])
            if parsed is not None:
                row[ci] = f"{parsed * fx_rate:.5f}"
        data_rows.append(row)
    base_count = len(data_rows)

    existing_ids = collect_existing_job_ids(str(output_dir), month, year)
    job_project_ids = build_job_project_ids(all_rows)

    projects_rows = parse_projects_rows(snapshot_dir / "projects_default.csv")
    orphan_rows = find_orphan_project_rows(
        projects_rows, job_project_ids, month, year, existing_ids, from_month=1
    )
    orphan_per_month: dict[int, int] = {}
    appended_rows: list[list[str]] = []
    for proj_row in orphan_rows:
        my = deadline_month_year(proj_row.get("Deadline", ""))
        rate = fx_for_month(my[0], my[1]) if my else fx_rate
        appended_rows.append(map_project_row(proj_row, rate))
        if my:
            orphan_per_month[my[0]] = orphan_per_month.get(my[0], 0) + 1

    late_rows, late_per_month = find_late_job_rows(
        all_rows, existing_ids, id_idx, deadline_idx, euro_idxs,
        month, year, fx_for_month,
    )
    appended_rows.extend(late_rows)

    # Filename from the snapshot's own timestamp — deterministic, never now().
    dd, mm, yyyy, hh, min_ = snapshot_timestamp(jobs_path)
    filename = f"XTRF-Job-{dd}-{mm}-{yyyy} {hh}_{min_} GMT+03_00 {month:02d}_{year}.csv"
    out_path = output_dir / filename

    # Write to a temp file and swap it in, so a failed run never leaves the
    # month without a file or with a truncated one.
    tmp_path = out_path.with_suffix(".csv.tmp")
    with open(tmp_path, "w", encoding="utf-8-sig", newline="") as f:
        f.write(f"Generated by XTRF on {dd}-{mm}-{yyyy} {hh}:{min_} GMT+03:00\n")
        f.write("," * 18 + "\n")
        writer = csv.writer(f, lineterminator="\n")
        writer.writerow(header)
        for row in data_rows:
            writer.writerow(row)
        for row in appended_rows:
            while len(row) < len(header):
                row.append("")
            writer.writerow(row[: len(header)])
    os.replace(tmp_path, out_path)

    # Replace, don't duplicate: drop any other file for this target month.
    for old in output_dir.glob("XTRF-Job-*.csv"):
        if old.name != filename and old.name.endswith(f" {month:02d}_{year}.csv"):
            old.unlink()

    _info(f"Enriched CSV written: {out_path}")
    _info(
        f"Row counts: {base_count} base jobs, {len(orphan_rows)} orphans appended "
        f"({', '.join(f'{m:02d}: {n}' for m, n in sorted(orphan_per_month.items()))}), "
        f"{len(late_rows)} late jobs appended "
        f"({', '.join(f'{m:02d}: {n}' for m, n in sorted(late_per_month.items()))})"
    )
    return {
        "base": base_count,
        "orphans": len(orphan_rows),
        "late": len(late_rows),
        "orphan_per_month": orphan_per_month,
        "late_per_month": late_per_month,
        "path": str(out_path),
    }


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Enrich one month of XTRF-style snapshots.")
    ap.add_argument("--snapshot", required=True, type=Path)
    ap.add_argument("--month", required=True, type=int)
    ap.add_argument("--year", required=True, type=int)
    ap.add_argument("--fx", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    args = ap.parse_args(argv)
    run(args.snapshot, args.month, args.year, args.fx, args.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
